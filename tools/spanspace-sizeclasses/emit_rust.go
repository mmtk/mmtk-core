// This file is part of mmtk-core's SpanSpace size-class generator (see gen.sh).
// It is derived from printClasses in Go's runtime/_mkmalloc/mksizeclasses.go,
// which it is compiled together with: makeClasses(), computeDivMagic() and
// printComment() are Go's own code, unmodified. Only the output format differs:
// this prints Rust instead of Go.

package main

import (
	"bytes"
	"fmt"
	"os"
)

func main() {
	classes := makeClasses()

	var comment bytes.Buffer
	printComment(&comment, classes)

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by tools/spanspace-sizeclasses/gen.sh; DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// Generated by Go's runtime/_mkmalloc/mksizeclasses.go, from:")
	fmt.Fprintf(&b, "// %s\n", os.Getenv("GO_REF"))
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// The tables are derived from Go. This implies no endorsement by Google or")
	fmt.Fprintln(&b, "// the Go contributors. Go's licence (BSD-3-Clause):")
	fmt.Fprintln(&b, "//")
	for _, line := range bytes.Split(bytes.TrimRight(goLicense, "\n"), []byte("\n")) {
		if len(line) == 0 {
			fmt.Fprintln(&b, "//")
		} else {
			fmt.Fprintf(&b, "// %s\n", line)
		}
	}
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "//! Go's small-object size classes (generated, see `tools/spanspace-sizeclasses`).")
	fmt.Fprintln(&b, "//!")
	fmt.Fprintln(&b, "//! ```text")
	for _, line := range bytes.Split(bytes.TrimRight(comment.Bytes(), "\n"), []byte("\n")) {
		line = bytes.TrimPrefix(line, []byte("// "))
		line = bytes.TrimPrefix(line, []byte("//"))
		if len(line) == 0 {
			fmt.Fprintln(&b, "//!")
		} else {
			fmt.Fprintf(&b, "//! %s\n", line)
		}
	}
	fmt.Fprintln(&b, "//! ```")
	fmt.Fprintln(&b)

	sizeToSizeClass := func(size int) int {
		for j, c := range classes {
			if c.size >= size {
				return j
			}
		}
		panic("unreachable")
	}

	fmt.Fprintf(&b, "pub const MIN_HEAP_ALIGN: usize = %d;\n", minHeapAlign)
	fmt.Fprintf(&b, "pub const MAX_SMALL_SIZE: usize = %d;\n", maxSmallSize)
	fmt.Fprintf(&b, "pub const SMALL_SIZE_DIV: usize = %d;\n", smallSizeDiv)
	fmt.Fprintf(&b, "pub const SMALL_SIZE_MAX: usize = %d;\n", smallSizeMax)
	fmt.Fprintf(&b, "pub const LARGE_SIZE_DIV: usize = %d;\n", largeSizeDiv)
	fmt.Fprintf(&b, "pub const NUM_SIZE_CLASSES: usize = %d;\n", len(classes))
	fmt.Fprintf(&b, "pub const PAGE_SHIFT: usize = %d;\n", pageShift)
	fmt.Fprintf(&b, "pub const MAX_OBJS_PER_SPAN: usize = %d;\n", maxObjsPerSpan(classes))
	fmt.Fprintf(&b, "pub const MAX_SIZE_CLASS_NPAGES: usize = %d;\n", maxNPages(classes))
	fmt.Fprintf(&b, "pub const TINY_SIZE: usize = %d;\n", tinySize)
	fmt.Fprintf(&b, "pub const TINY_SIZE_CLASS: usize = %d;\n", sizeToSizeClass(tinySize))
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "#[rustfmt::skip]")
	fmt.Fprint(&b, "pub const SIZE_CLASS_TO_SIZE: [u16; NUM_SIZE_CLASSES] = [")
	for _, c := range classes {
		fmt.Fprintf(&b, "%d, ", c.size)
	}
	fmt.Fprintln(&b, "];")

	fmt.Fprintln(&b, "#[rustfmt::skip]")
	fmt.Fprint(&b, "pub const SIZE_CLASS_TO_NPAGES: [u8; NUM_SIZE_CLASSES] = [")
	for _, c := range classes {
		fmt.Fprintf(&b, "%d, ", c.npages)
	}
	fmt.Fprintln(&b, "];")

	fmt.Fprintln(&b, "#[rustfmt::skip]")
	fmt.Fprint(&b, "pub const SIZE_CLASS_TO_DIV_MAGIC: [u32; NUM_SIZE_CLASSES] = [")
	for _, c := range classes {
		if c.size == 0 {
			fmt.Fprintf(&b, "0, ")
			continue
		}
		fmt.Fprintf(&b, "u32::MAX / %d + 1, ", c.size)
	}
	fmt.Fprintln(&b, "];")

	sc := make([]int, smallSizeMax/smallSizeDiv+1)
	for i := range sc {
		sc[i] = sizeToSizeClass(i * smallSizeDiv)
	}
	fmt.Fprintln(&b, "#[rustfmt::skip]")
	fmt.Fprint(&b, "pub const SIZE_TO_SIZE_CLASS8: [u8; SMALL_SIZE_MAX / SMALL_SIZE_DIV + 1] = [")
	for _, v := range sc {
		fmt.Fprintf(&b, "%d, ", v)
	}
	fmt.Fprintln(&b, "];")

	sc = make([]int, (maxSmallSize-smallSizeMax)/largeSizeDiv+1)
	for i := range sc {
		sc[i] = sizeToSizeClass(smallSizeMax + i*largeSizeDiv)
	}
	fmt.Fprintln(&b, "#[rustfmt::skip]")
	fmt.Fprint(&b, "pub const SIZE_TO_SIZE_CLASS128: [u8; (MAX_SMALL_SIZE - SMALL_SIZE_MAX) / LARGE_SIZE_DIV + 1] = [")
	for _, v := range sc {
		fmt.Fprintf(&b, "%d, ", v)
	}
	fmt.Fprintln(&b, "];")

	os.Stdout.Write(b.Bytes())
}
